# -*- coding: utf-8 -*-
"""Генерирует ПРОМТ_для_ChatGPT.md — самодостаточный промт со всеми данными каталога."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from data import CATEGORIES, PRODUCTS  # noqa: E402


def is_tbd(r):
    return len(r) > 2 and r[2] == "tbd"


def val(r):
    if is_tbd(r):
        return "УТОЧНИТЬ" if r[1] in ("—", "", None) else r[1] + " (?)"
    return r[1]


def table():
    cat = {c["id"]: c["title"] for c in CATEGORIES}
    out = ["| Группа | Модель Irbis | Платформа | Параметр 1 | Параметр 2 | Параметр 3 | Прочее | Метка |",
           "|---|---|---|---|---|---|---|---|"]
    for c in CATEGORIES:
        for p in [x for x in PRODUCTS if x["cat"] == c["id"]]:
            k = p["key"]
            other = "; ".join("%s: %s" % (r[0], val(r)) for r in p.get("specs", [])) or "—"
            flag = "ДЕФЕКТ" if p.get("note") else ""
            out.append("| %s | %s | %s | %s: %s | %s: %s | %s: %s | %s | %s |" % (
                cat[p["cat"]], p["name"], p.get("analog", "—"),
                k[0][0], val(k[0]), k[1][0], val(k[1]), k[2][0], val(k[2]), other, flag))
    return "\n".join(out)


def defects():
    out = []
    n = 0
    for p in PRODUCTS:
        if p.get("note"):
            n += 1
            out.append("%d. **%s** — %s" % (n, p["name"], p["note"]))
    return "\n".join(out)


def gaps():
    out = []
    for p in PRODUCTS:
        miss = [r[0] for r in p["key"] if is_tbd(r)]
        miss += [r[0] for r in p.get("specs", []) if is_tbd(r)]
        if miss:
            out.append("- **%s** (%s): %s" % (p["name"], p.get("analog", "—"), ", ".join(miss)))
    return "\n".join(out)


def keys_block():
    return "\n".join("- **%s** — %s" % (c["title"], " · ".join(c["keys"])) for c in CATEGORIES)


BODY = """# ПРОМТ ДЛЯ ChatGPT — доработка каталога спецтехники Irbis

*Скопируй весь текст ниже, начиная со строки «Ты — технический редактор», и вставь в ChatGPT одним сообщением.*

---

Ты — технический редактор каталогов спецтехники. Твоя задача — довести до чистового
вида каталог бренда **Irbis**: устранить дефекты данных, заполнить пропуски, привести
обозначения к единому виду и добавить одну новую товарную группу.

## 1. Контекст

Irbis — торговая марка спецтехники. Машины строятся на платформах XCMG, SEM и
NHL/Terex. В клиентской версии каталога указывается **только обозначение Irbis**;
колонка «Платформа» — служебная, нужна для сверки характеристик и в готовый каталог
не выносится.

Каталог уже собран: {n_cats} товарных групп, {n_models} моделей. Часть значений
подтверждена по дилерским каталогам, часть — нет.

## 2. Обозначения в данных

- `УТОЧНИТЬ` — значение отсутствует, его нужно найти.
- `(?)` после значения — значение есть, но не подтверждено; нужно перепроверить.
- Метка `ДЕФЕКТ` в последней колонке — у позиции есть конкретная проблема, описанная в §6.

## 3. Ключевые параметры групп

В карточке каждой машины на первом месте стоят три параметра своей группы —
именно эти, в этом порядке, менять состав нельзя:

{keys}

## 4. Полные данные каталога

{table}

## 5. Что нужно сделать

1. **Устранить дефекты** из §6 — по каждому дай решение и обоснование.
2. **Заполнить пропуски** из §7 — по каждому значению укажи источник (сайт + модель,
   по которой сверял). Если подтверждения нет — так и напиши, значение не выдумывай.
3. **Выровнять обозначения** по правилам §8.
4. **Добавить восьмую группу — навесное оборудование** по §9.
5. **Выдать результат** в формате §10.

## 6. Дефекты, которые надо устранить

{defects}

## 7. Пропуски, которые надо заполнить

{gaps}

## 8. Выравнивание обозначений

Сейчас система индексов разнородна: где-то за основу взят индекс платформы
(XE60WD, XCT55, D360), где-то собственный числовой индекс (IR30, IR958),
где-то смешанный (IR6-3507K и IR3207K в одной группе).

Сделай так:

1. **Сохрани текущие обозначения как основные** — они уже в обороте, менять их
   без моего решения нельзя.
2. Найди и перечисли **все места, где система ломается**: дубли индексов, разный
   формат внутри одной группы, индекс, не отражающий параметр машины.
3. Отдельной колонкой **предложи единую схему** обозначений на весь каталог —
   такую, чтобы по индексу читались группа и главный параметр машины, и чтобы
   в ней не возникало дублей. Дай её как предложение с обоснованием, не переписывая
   каталог автоматически.
4. Проверь единообразие записи величин: единицы (т, кВт, л.с., м³, мм, м),
   десятичный разделитель — запятая, диапазоны через тире (4,2–7,0 м³),
   мощность в формате «261 кВт (350 л.с.)».

## 9. Новая группа: навесное оборудование

Добавь восьмую группу — **навесное оборудование** — и наполни её по тем же
правилам, что и остальные: три ключевых параметра в карточке, полная спецификация,
пометка неподтверждённых значений.

Состав группы и ключевые параметры для каждого типа:

| Тип | Ключевые параметры |
|---|---|
| Ковши экскаваторные (стандартный, скальный, планировочный, траншейный) | ёмкость, ширина, класс машины-носителя |
| Ковши погрузочные (стандартный, скальный, увеличенный, зерновой) | ёмкость, ширина, масса |
| Гидромолоты (закрытого типа, с боковым захватом) | энергия удара, частота, класс носителя |
| Грейферы (двухчелюстные, многочелюстные) | ёмкость, число челюстей, масса |
| Бревнозахваты | площадь захвата, масса, класс носителя |
| Гидроножницы и измельчители | усилие резания, раскрытие челюстей, масса |
| Рыхлители (одно- и трёхстоечные) | число стоек, глубина рыхления, масса |
| Быстросъёмные соединители | тип (механический/гидравлический), класс машины, масса |
| Вилы паллетные | грузоподъёмность, длина вил, класс носителя |
| Отвалы (прямой, поворотный, снежный) | ширина, объём, масса |
| Щётки дорожные | ширина захвата, тип привода, масса |
| Буры шнековые | диаметр, глубина бурения, крутящий момент |
| Крюк-стрелы и люльки для телескопов | грузоподъёмность, вылет, масса |

Для каждого типа укажи, **с какими машинами каталога он совместим** — по классу
и массе носителя. Это главная ценность раздела: клиент должен видеть, что подходит
к его машине.

## 10. Формат результата

Выдай по порядку:

1. **Отчёт по дефектам** — таблица: позиция → что не так → решение → источник.
2. **Отчёт по пропускам** — таблица: позиция → параметр → найденное значение →
   источник → уверенность (подтверждено / требует проверки / не найдено).
3. **Замечания по обозначениям** — список поломок системы + предложенная единая схема.
4. **Сводная таблица каталога** — все {n_models} моделей плюс навесное оборудование,
   колонки: группа, модель, три ключевых параметра, прочие характеристики, статус данных.
5. **Готовый каталог одним HTML-файлом** — офлайн, без внешних зависимостей кроме
   шрифтов, с поиском по моделям, фильтром по группам, блоками под фотографии
   (`<img src="photos/<код>.jpg">` с запасной схемой при отсутствии файла)
   и разделом «Открытые вопросы» внизу.

## 11. Запреты

- **Не выдумывай характеристики.** Если значение не найдено в открытых источниках —
  пиши «не найдено» и оставляй пометку. Правдоподобное, но непроверенное число
  в коммерческом каталоге хуже пустой ячейки.
- Не меняй состав трёх ключевых параметров у групп.
- Не переименовывай модели самостоятельно — только предлагай.
- Не подставляй характеристики одной модели другой «по аналогии с классом».
- Не выноси в клиентскую часть названия платформ (XCMG, SEM, NHL/Terex) —
  они только в служебной колонке.
"""


if __name__ == "__main__":
    text = BODY.format(
        n_cats=len(CATEGORIES), n_models=len(PRODUCTS),
        keys=keys_block(), table=table(), defects=defects(), gaps=gaps())
    out = os.path.join(HERE, "ПРОМТ_для_ChatGPT.md")
    with open(out, "w", encoding="utf-8") as f:
        f.write(text)
    print("  →", out, "(%.1f КБ, %d строк)" % (len(text.encode()) / 1024, text.count("\n") + 1))
